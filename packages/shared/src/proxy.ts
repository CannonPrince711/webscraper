/**
 * Proxy vocabulary — shared by the wizard, the API routes and the engine.
 *
 * The rule this module exists to enforce:
 *
 * **A saved job describes *where* its traffic should leave from, never *how* to
 * authenticate.** `fetch.proxy` therefore holds one of three things:
 *
 * | Value                        | Meaning                                          |
 * | ---------------------------- | ------------------------------------------------ |
 * | `null`                       | Direct connection (or the server's static pool).  |
 * | `decodo` / `decodo://?…`     | Managed residential, credentials from the engine. |
 * | `http://user:pass@host:port` | An explicit proxy. Credentials end up in the job. |
 *
 * The third form is supported because self-hosted proxies are legitimate, but
 * the wizard steers users to the second one for exactly the reason it is
 * listed second: a job config is read back by the API, rendered in the UI,
 * exported to JSON and copied into bug reports. Nothing secret belongs in it.
 *
 * The string is deliberately *not* a URL with a scheme per provider: the engine
 * is the only component that knows which providers exist and what a credential
 * means, so the client stays a dumb builder of a documented string.
 */

export const PROXY_KINDS = ['direct', 'decodo', 'custom'] as const;
export type ProxyKind = (typeof PROXY_KINDS)[number];

/** The literal a job stores when it wants the engine's default proxy. */
export const DECODO_PROXY_VALUE = 'decodo';

export interface ProxySelection {
  kind: ProxyKind;
  /** ISO-3166 alpha-2, or null for the account default. */
  country?: string | null;
  city?: string | null;
  /** Sticky-session id. Generated by the wizard when sticky is enabled. */
  session?: string | null;
  /** Sticky-session lifetime in minutes (Decodo allows 1–1440). */
  stickyMinutes?: number | null;
  /** Only for `kind: 'custom'`. */
  customUrl?: string | null;
}

