/**
 * Turn a selection into the string a job stores.
 *
 * Empty selection and a direct connection both produce `null`, because "the
 * default" and "no proxy" must not be two different states in the database.
 */
export function buildProxyValue(selection: ProxySelection): string | null {
  if (selection.kind === 'direct') return null;

  if (selection.kind === 'custom') {
    const url = selection.customUrl?.trim();
    return url && url.length > 0 ? url : null;
  }

  const params = new URLSearchParams();
  if (selection.country) params.set('country', selection.country.toLowerCase());
  if (selection.city) params.set('city', selection.city.trim().toLowerCase().replace(/\s+/g, '_'));
  if (selection.session) params.set('session', selection.session);
  if (selection.stickyMinutes) {
    params.set('sticky', String(Math.min(1440, Math.max(1, Math.round(selection.stickyMinutes)))));
  }

  const query = params.toString();
  return query ? `decodo://?${query}` : DECODO_PROXY_VALUE;
}

/** Read a stored value back into the form, so editing a job is not lossy. */
export function parseProxyValue(value: string | null | undefined): ProxySelection {
  if (!value || value.trim().length === 0) return { kind: 'direct' };

  const raw = value.trim();
  if (!raw.toLowerCase().startsWith('decodo')) return { kind: 'custom', customUrl: raw };

  const query = raw.slice('decodo'.length).replace(/^[:/]*/, '').replace(/^\?/, '');
  if (!query) return { kind: 'decodo' };

  try {
    const params = new URLSearchParams(query);
    const sticky = Number(params.get('sticky'));
    return {
      kind: 'decodo',
      country: params.get('country'),
      city: params.get('city'),
      session: params.get('session'),
      stickyMinutes: Number.isFinite(sticky) && sticky > 0 ? sticky : null,
    };
  } catch {
    return { kind: 'decodo' };
  }
}

export interface ProxyDescription {
  kind: ProxyKind;
  /** Short badge text. */
  label: string;
  /** One sentence of context for a tooltip or a details row. */
  detail: string;
  /** True when the stored value may contain a credential. */
  carriesCredentials: boolean;
}

/**
 * Describe a stored value for display.
 *
 * Never returns the credential part of a custom proxy URL — this output is
 * rendered in the UI and copied into support tickets.
 */
export function describeProxy(value: string | null | undefined): ProxyDescription {
  if (!value || value.trim().length === 0) {
    return {
      kind: 'direct',
      label: 'Direct',
      detail: 'Traffic leaves from the engine’s own IP address.',
      carriesCredentials: false,
    };
  }

  const raw = value.trim();
  if (!raw.toLowerCase().startsWith('decodo')) {
    return {
      kind: 'custom',
      label: 'Custom proxy',
      detail: `Traffic leaves through ${safeHost(raw)}.`,
      carriesCredentials: raw.includes('@'),
    };
  }

  const parsed = parseProxyValue(raw);
  const bits: string[] = [];
  if (parsed.country) {
    bits.push(DECODO_COUNTRIES.find((entry) => entry.code === parsed.country)?.label ?? parsed.country.toUpperCase());
  }
  if (parsed.city) bits.push(titleCase(parsed.city.replace(/_/g, ' ')));

  const mode = parsed.session
    ? `sticky IP for ${parsed.stickyMinutes ?? 10} min`
    : 'rotating IP';

  return {
    kind: 'decodo',
    label: bits.length > 0 ? `Decodo · ${bits.join(' · ')}` : 'Decodo',
    detail: `Residential addresses from Decodo, ${mode}. Credentials come from the engine’s environment.`,
    carriesCredentials: false,
  };
}

/** True when a job needs Decodo credentials to be configured server-side. */
export function usesDecodo(value: string | null | undefined): boolean {
  return Boolean(value && value.trim().toLowerCase().startsWith('decodo'));
}

/** A sticky-session id. Short, URL-safe, and unique per job run. */
export function newProxySessionId(): string {
  const cryptoApi = globalThis.crypto;
  if (cryptoApi && typeof cryptoApi.randomUUID === 'function') {
    return `ws${cryptoApi.randomUUID().replace(/-/g, '').slice(0, 12)}`;
  }
  return `ws${Math.random().toString(36).slice(2, 14)}`;
}

// ---------------------------------------------------------------------------
function titleCase(input: string): string {
  return input.replace(/\b[a-z]/g, (character) => character.toUpperCase());
}

function safeHost(url: string): string {
  try {
    return new URL(url).host || 'a proxy';
  } catch {
    return 'a proxy';
  }
}
